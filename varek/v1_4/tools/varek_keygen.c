// varek_keygen.c — make an ECDSA P-384 key pair for signing the Warden's
// verdict stream (v1.41; was Ed25519/libsodium through v1.40).
//
//   varek_keygen <keyfile>
//
// Writes <keyfile>: a PKCS#8 PEM private key on curve P-384, mode 0600, and
// <keyfile>.pub: the uncompressed public point as hex. Neither may exist
// already. Prints the public point hex. Run the Warden with --sign-key
// <keyfile>; give auditors <keyfile>.pub (tools/varek_audit.py --pubkey). Keep
// the key where the log's holder cannot read it, or the signatures prove
// nothing against that holder.
//
// The key is generated by the host OpenSSL provider through varek_fips; this
// tool performs no cryptography of its own and only writes the files.

#include "../varek_fips.h"

#include <errno.h>
#include <fcntl.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sys/stat.h>
#include <unistd.h>

static int write_new(const char *path, const char *text, mode_t mode) {
    int fd = open(path, O_WRONLY | O_CREAT | O_EXCL | O_CLOEXEC | O_NOFOLLOW, mode);
    if (fd < 0) {
        fprintf(stderr, "varek_keygen: %s: %s\n", path, strerror(errno));
        return -1;
    }
    size_t len = strlen(text);
    ssize_t w = write(fd, text, len);
    if (w != (ssize_t)len || fsync(fd) != 0 || close(fd) != 0) {
        fprintf(stderr, "varek_keygen: %s: write failed\n", path);
        unlink(path);
        return -1;
    }
    return 0;
}

int main(int argc, char **argv) {
    if (argc != 2) {
        fprintf(stderr, "usage: %s <keyfile>   (writes <keyfile> and <keyfile>.pub)\n", argv[0]);
        return 2;
    }
    char why[256] = {0};
    if (vfips_init(VFIPS_INIT_SECURE_HEAP, why, sizeof why) != 0) {
        fprintf(stderr, "varek_keygen: crypto init failed: %s\n", why);
        return 1;
    }
    size_t kl = strlen(argv[1]);
    char *pub = malloc(kl + 5);
    if (!pub) return 1;
    memcpy(pub, argv[1], kl);
    memcpy(pub + kl, ".pub", 5);

    char pem[4096];
    char pk_hex[VFIPS_PUB_HEX_MAX + 1];
    if (vfips_keygen_pem(pem, sizeof pem, pk_hex, sizeof pk_hex) != 0) {
        fprintf(stderr, "varek_keygen: key generation failed\n");
        free(pub);
        return 1;
    }
    size_t hl = strlen(pk_hex);
    pk_hex[hl] = '\n';
    pk_hex[hl + 1] = '\0';

    int rc = 0;
    if (write_new(argv[1], pem, 0600) < 0) rc = 1;
    else if (write_new(pub, pk_hex, 0644) < 0) { unlink(argv[1]); rc = 1; }
    vfips_memzero(pem, sizeof pem);
    if (rc == 0) printf("%s", pk_hex);
    free(pub);
    return rc;
}
